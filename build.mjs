// Build lib/client.js: src/client bundled with three.js, React left to dsh,
// wrapped in dsh's browser module loader like every other client plugin.
//
// esbuild and three are this package's own devDependencies. The bundler runs as
// WebAssembly inside this Node process (esbuild-wasm), because the native
// esbuild child process is denied directory access under the dsh sandbox on
// Windows; the wasm build produces the same bundle without spawning anything.
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const esbuild = require('esbuild-wasm');

await esbuild.initialize({});

const result = await esbuild.build({
  entryPoints: [join(here, 'src/client/index.js')],
  absWorkingDir: here,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});

const body = result.outputFiles[0].text;
const wrapped = `// blender-preview — browser half. GENERATED by build.mjs from src/client; edit those, then npm run build.
// Bundles three.js (MIT, https://threejs.org).
window.__ModuleLoader__.load({
  id: "blender-preview",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`;
mkdirSync(join(here, 'lib'), { recursive: true });
writeFileSync(join(here, 'lib/client.js'), wrapped);
console.log(`lib/client.js ${(wrapped.length / 1024).toFixed(0)} KB`);
